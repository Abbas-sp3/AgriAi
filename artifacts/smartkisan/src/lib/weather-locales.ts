export function farmingAdviceKey(
  temp: number,
  precipitation: number,
  humidity: number,
): AdviceKey {
  if (precipitation > 20) return "heavy_rain";
  if (precipitation > 5) return "moderate_rain";
  if (temp > 38) return "hot";
  if (temp < 10) return "cold";
  if (humidity > 85) return "high_humidity";
  if (humidity < 30) return "low_humidity";
  return "favorable";
}

export function translateFarmingAdvice(lang: LangCode, temp: number, precipitation: number, humidity: number): string {
  const key = farmingAdviceKey(temp, precipitation, humidity);
  const table = ADVICE[lang] ?? ADVICE.en;
  return table[key] ?? ADVICE.en[key];
}
